CREATE TABLE IF NOT EXISTS clans (
  id VARCHAR(64) PRIMARY KEY,
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS agents (
  id VARCHAR(64) PRIMARY KEY, username VARCHAR(64) NOT NULL UNIQUE, clan_id VARCHAR(64), profile JSON NOT NULL, FOREIGN KEY (clan_id) REFERENCES clans(id),
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS agent_states (
  agent_id VARCHAR(64) NOT NULL, FOREIGN KEY (agent_id) REFERENCES agents(id), PRIMARY KEY(agent_id), snapshot JSON NOT NULL,
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS agent_memories (
  id BIGINT AUTO_INCREMENT PRIMARY KEY, agent_id VARCHAR(64) NOT NULL, FOREIGN KEY (agent_id) REFERENCES agents(id), memory JSON NOT NULL, INDEX(agent_id,created_at),
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ai_decisions (
  id CHAR(36) PRIMARY KEY, agent_id VARCHAR(64) NOT NULL, FOREIGN KEY (agent_id) REFERENCES agents(id), decision JSON NOT NULL, INDEX(agent_id,created_at),
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS system_events (
  id CHAR(36) PRIMARY KEY, agent_id VARCHAR(64), FOREIGN KEY (agent_id) REFERENCES agents(id), event_type VARCHAR(48) NOT NULL, envelope JSON NOT NULL, INDEX(event_type,created_at),
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS tasks (
  id CHAR(36) PRIMARY KEY, agent_id VARCHAR(64) NOT NULL, FOREIGN KEY (agent_id) REFERENCES agents(id), status VARCHAR(32) NOT NULL, detail JSON NOT NULL, INDEX(agent_id,status),
  created_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3), updated_at TIMESTAMP(3) DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB;
